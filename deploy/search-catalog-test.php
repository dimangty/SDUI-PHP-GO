<?php
declare(strict_types=1);
require '/app/vendor/autoload.php';
require __DIR__.'/search-security-provision.php';

use Shop\infrastructure\{Database,Env,OpenSearch};
use Shop\repositories\ShopRepository;
use Shop\application\CatalogService;

try {
    if (getenv('SEARCH_PRIVILEGES_DISPOSABLE') !== '1') { throw new RuntimeException('Disposable test opt-in required'); }
    $admin = new Database(Env::get('SEARCH_TEST_DATABASE_URL'));
    // Small real PostgreSQL fixture, not an SQL migration/preflight acceptance
    // substitute. No existing database or index is opened by this fixture.
    $admin->execute('CREATE TABLE categories(id uuid PRIMARY KEY,name text,parent_id uuid,icon_url text,sort_order int DEFAULT 0)');
    $admin->execute('CREATE TABLE products(id uuid PRIMARY KEY,category_id uuid,name text,description text,price numeric(12,2),discount_price numeric(12,2),stock int,is_active bool DEFAULT true,rating double precision,created_at timestamptz DEFAULT now())');
    $admin->execute('CREATE TABLE product_images(id bigint GENERATED BY DEFAULT AS IDENTITY,product_id uuid,url text,sort_order int)');
    $admin->execute('CREATE TABLE reviews(product_id uuid)');
    $admin->execute('CREATE TABLE orders(id uuid,status text)');
    $admin->execute('CREATE TABLE order_items(order_id uuid,product_id uuid,quantity int)');
    foreach (['runtime','reconcile','indexer'] as $role) {
        $secret = Env::get('SEARCH_TEST_SQL_'.strtoupper($role).'_PASSWORD');
        if (!preg_match('/^[A-Za-z0-9_-]{32,}$/D', $secret)) { throw new RuntimeException('Invalid test SQL credential'); }
        $admin->execute("CREATE ROLE shopkmp_$role LOGIN PASSWORD '$secret'");
        $admin->execute("GRANT USAGE ON SCHEMA public TO shopkmp_$role");
        $admin->execute("GRANT SELECT ON ALL TABLES IN SCHEMA public TO shopkmp_$role");
    }
    $admin->execute('GRANT INSERT,UPDATE,DELETE ON products,product_images TO shopkmp_runtime');
    $admin->execute('GRANT USAGE ON SEQUENCE product_images_id_seq TO shopkmp_runtime');
    $admin->execute('GRANT UPDATE ON categories,products,product_images,reviews TO shopkmp_indexer');
    $category = '00000000-0000-4000-8000-000000000003';
    $admin->execute('INSERT INTO categories(id,name) VALUES(?,?)', [$category,'Native catalog fixture']);
    $index = 'shopkmp-products-native-proof';
    putenv('OPENSEARCH_PRODUCTS_INDEX='.$index);
    searchProvision('upgrade');
    // A true conflicting legacy template outranks the managed priority-100
    // template. The application create body must still be safe on an empty build.
    $externalTemplate = '/_index_template/round7-external-high-priority';
    [$status,$ack] = searchRequest('PUT',$externalTemplate,[
        'index_patterns'=>['shopkmp-products-native-*'],'priority'=>1000,
        'template'=>['settings'=>['number_of_shards'=>1,'number_of_replicas'=>0],
            'mappings'=>['dynamic'=>true,'properties'=>['externalOnly'=>['type'=>'keyword']]]],
        '_meta'=>['owner'=>'independent-legacy-template-fixture'],
    ]);
    if($status!==200 || ($ack['acknowledged']??null)!==true){throw new RuntimeException('Cannot install conflicting external template');}
    [$status,$externalBefore] = searchRequest('GET',$externalTemplate);
    if($status!==200){throw new RuntimeException('Cannot inventory external template');}
    searchCatalogSchema();
    $connect = static function(string $role): array {
        $db = new Database('postgres://shopkmp_'.$role.':'.Env::get('SEARCH_TEST_SQL_'.strtoupper($role).'_PASSWORD').'@postgres:5432/shopkmp?sslmode=verify-full');
        putenv('OPENSEARCH_URL=https://shopkmp_'.$role.':'.Env::get('OPENSEARCH_'.strtoupper($role).'_PASSWORD').'@opensearch:9200');
        return [$db, new ShopRepository($db)];
    };
    [$db,$repo] = $connect('indexer');
    $result = (new OpenSearch($db,$repo))->bootstrap(10,30);
    if (!$result['created'] || $result['inventory']['documents'] !== 0) { throw new RuntimeException('Native bootstrap failed'); }
    print "native indexer OpenSearch::bootstrap: created verified empty index\n";
    $empty = (new OpenSearch($db,$repo))->stage('shopkmp-products-native-empty-stage',10,30);
    if(!$empty['created'] || $empty['inventory']['documents']!==0){throw new RuntimeException('Native empty stage failed');}
    $index='shopkmp-products-native-empty-stage'; putenv('OPENSEARCH_PRODUCTS_INDEX='.$index);
    searchProvision('upgrade');
    [$status,$emptyInfo]=searchRequest('GET','/'.$index);
    print 'native empty stage under priority-1000 external template: dynamic='.json_encode($emptyInfo[$index]['mappings']['dynamic']??null)."\n";
    [$db,$repo] = $connect('runtime');
    $catalog = new CatalogService($db,$repo);
    $dto = $catalog->createProduct(['categoryId'=>$category,'name'=>'Native scoped catalog writer','description'=>'Actual SQL and TLS OpenSearch',
        'price'=>'50.01','stock'=>5,'imageUrls'=>['/native.png']]);
    $id = $dto['id'];
    [$status,$doc] = searchRequest('GET', '/'.$index.'/_doc/'.$id);
    print 'native runtime catalog document readback under conflicting template: HTTP '.$status."\n";
    if ($status !== 200 || $doc['_source']['name'] !== $dto['name'] || $doc['_source']['price'] !== '50.01'
        || $doc['_source']['imageUrls'] !== ['/native.png']) { throw new RuntimeException('Runtime catalog create did not write full source'); }
    $catalog->updateProduct($id, ['name'=>'Updated native scoped catalog writer']);
    $page = $catalog->products(['q'=>'Updated native'], true);
    if (($page['items'][0]['id'] ?? null) !== $id) { throw new RuntimeException('Runtime catalog update/search failed'); }
    print "native runtime CatalogService create/update/search: actual SQL + full-source TLS document writes passed\n";
    if(!in_array($emptyInfo[$index]['mappings']['dynamic']??null,[false,'false'],true)){
        throw new RuntimeException('Empty stage inherited unsafe dynamic mapping');
    }
    searchCatalogSchema();
    [$status,$externalAfter]=searchRequest('GET',$externalTemplate);
    if($status!==200 || $externalAfter!==$externalBefore){throw new RuntimeException('External template was modified');}
    print "actual schema acknowledgement/readback verified; higher-priority external template preserved\n";
    [$db,$repo] = $connect('reconcile');
    if ((new OpenSearch($db,$repo))->reindex(10,30) !== 1) { throw new RuntimeException('Native reconciliation failed'); }
    print "native reconcile OpenSearch::reindex: SQL read-only + existing-index write/refresh passed\n";
    [$db,$repo] = $connect('indexer');
    $stage = (new OpenSearch($db,$repo))->stage('shopkmp-products-native-stage',10,30);
    if (!$stage['created'] || $stage['inventory']['documents'] !== 1) { throw new RuntimeException('Native stage failed'); }
    print "native indexer OpenSearch::stage: SHARE locks + scoped create/mapping/refresh/scroll/publication passed\n";
    [$db,$repo] = $connect('runtime');
    (new CatalogService($db,$repo))->deleteProduct($id);
    [$status] = searchRequest('GET', '/'.$index.'/_doc/'.$id);
    if ($status !== 404) { throw new RuntimeException('Runtime catalog deactivation did not delete document'); }
    print "native runtime CatalogService::deleteProduct: SQL deactivation + TLS document delete passed\n";
    putenv('OPENSEARCH_PRODUCTS_INDEX');
    searchProvision('upgrade');
} catch (Throwable $error) {
    // Do not emit SQL/DSN exception arguments or generated credentials.
    fwrite(STDERR, 'NATIVE_CATALOG_PRIVILEGES_FAILED: '.get_class($error)."\n");
    exit(1);
}
